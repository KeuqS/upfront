"""Generate docs/api.md from the public API's signatures and docstrings.

uv run python scripts/gen_api_docs.py          # write docs/api.md
uv run python scripts/gen_api_docs.py --check  # exit 1 if docs/api.md is stale
"""

from __future__ import annotations

import dataclasses
import inspect
import sys
from pathlib import Path

from upfront import compat, discover, fetch, report, tokens

OUT = Path(__file__).resolve().parent.parent / "docs" / "api.md"

SECTIONS = [
    (
        "Profiling",
        [
            report.profile,
            report.profile_tools_file,
            report.Report,
            report.HarnessReport,
            report.ServerUsage,
            report.ToolUsage,
            report.FileUsage,
        ],
    ),
    (
        "Discovery",
        [
            discover.discover,
            discover.Discovery,
            discover.HarnessContext,
            discover.ServerSpec,
            discover.Skill,
            discover.InstructionFile,
        ],
    ),
    ("Fetching", [fetch.fetch_all, fetch.fetch_one, fetch.ServerResult]),
    ("Tokens", [tokens.count, tokens.tool_tokens, tokens.skill_tokens, tokens.tokenizer_name]),
    ("Compatibility", [compat.check_tools, compat.check_skills, compat.Finding, compat.Rule]),
]


def render() -> str:
    out = [
        "# API reference",
        "",
        "Generated by `scripts/gen_api_docs.py` from the code; do not edit by hand.",
        "Everything below is importable from its module; `profile`, `profile_tools_file` and",
        "`Report` are also exported from `upfront`.",
    ]
    for title, objs in SECTIONS:
        out += ["", f"## {title}"]
        for obj in objs:
            mod = obj.__module__
            name = obj.__name__
            if inspect.isclass(obj) and dataclasses.is_dataclass(obj):
                fields = ", ".join(f.name for f in dataclasses.fields(obj))
                out += ["", f"### `{mod}.{name}`", "", f"Dataclass with fields: `{fields}`."]
            else:
                out += ["", f"### `{mod}.{name}{inspect.signature(obj, eval_str=True)}`"]
            doc = inspect.getdoc(obj)
            if doc and not doc.startswith(f"{name}("):
                out += ["", doc]
    rules = [
        "",
        "## Compatibility rules",
        "",
        "| id | harness | severity | rule | source |",
        "|---|---|---|---|---|",
    ]
    for r in compat.RULES.values():
        summary = r.summary.replace("<", "&lt;")  # GitHub would treat <server> as an HTML tag
        harnesses = ", ".join(r.harnesses)
        rules.append(
            f"| `{r.id}` | {harnesses} | {r.severity} | {summary} | [source]({r.source}) |"
        )
    return "\n".join(out + rules) + "\n"


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        if not OUT.is_file() or OUT.read_text() != text:
            sys.exit("docs/api.md is stale: run `uv run python scripts/gen_api_docs.py`")
    else:
        OUT.write_text(text)
